# === Системные сервисы и ISO-образы (инфопанель вверху страницы) ===========

# DHCP и TFTP — часто разные пакеты в разных дистрибутивах/окружениях,
# поэтому проверяем по очереди список кандидатов и берём первый, про
# который systemctl вообще что-то знает. Если ни один сервис не известен
# systemd (например, его вообще нет в системе), в качестве запасного
# варианта проверяем, слушает ли что-нибудь стандартный порт протокола.
