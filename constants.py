# === Режим прослушки: обнаружение MAC-адресов в сети =======================
# Два независимых способа узнать, какие устройства "видны" в сети — человек
# выбирает один из них в окне прослушки:
#
# Вариант 1 — tcpdump на активном сетевом интерфейсе сервера: пассивно
# слушает трафик и вытаскивает MAC (и IP, когда виден в ARP/IP-заголовке)
# из проходящих пакетов. Ничего никуда не отправляет, только слушает.
#
# Вариант 2 — SSH на коммутатор MikroTik и таблица его bridge host print:
# показывает, какие MAC-адреса реально подключены к каким портам/VLAN'ам
# коммутатора. Адрес коммутатора человек вводит в интерфейсе, логин — ниже.
TCPDUMP_INTERFACE_FALLBACK = "eth0"  # если не получилось определить активный интерфейс автоматически
TCPDUMP_RAW_LINES_LIMIT = 200        # сколько последних строк вывода tcpdump хранить для показа в интерфейсе

